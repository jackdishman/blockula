use std::path::{Path, PathBuf};

fn git(args: &[&str]) -> Option<String> {
    let out = std::process::Command::new("git").args(args).output().ok()?;
    out.status
        .success()
        .then(|| String::from_utf8_lossy(&out.stdout).trim().to_string())
}

fn main() {
    // Embed the git commit (if built from a checkout) for /api/status and /metrics.
    if let Some(sha) = git(&["rev-parse", "--short=12", "HEAD"]) {
        println!("cargo:rustc-env=BLOCKULA_GIT_SHA={sha}");
    }
    // Rerun when HEAD moves. Ask git where HEAD lives: in a worktree `.git` is a file, and a
    // path that doesn't exist makes cargo rerun this script, and rebuild the crate, every time.
    if let Some(head) = git(&["rev-parse", "--path-format=absolute", "--git-path", "HEAD"]) {
        println!("cargo:rerun-if-changed={head}");
    }
    println!("cargo:rerun-if-env-changed=BLOCKULA_GIT_SHA");
    wallet();
}

/// Files worth gzipping: text. Fonts and images are compressed already.
fn compressible(path: &str) -> bool {
    [
        ".html",
        ".js",
        ".css",
        ".txt",
        ".json",
        ".svg",
        ".map",
        ".webmanifest",
    ]
    .iter()
    .any(|e| path.ends_with(e))
}

fn walk(dir: &Path, rel: &str, out: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<_> = std::fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("reading {}: {e}", dir.display()))
        .map(|e| e.expect("a directory entry"))
        .collect();
    entries.sort_by_key(|e| e.file_name());
    for e in entries {
        let name = e
            .file_name()
            .into_string()
            .unwrap_or_else(|n| panic!("{n:?} in the wallet export isn't UTF-8"));
        let path = if rel.is_empty() {
            name
        } else {
            format!("{rel}/{name}")
        };
        let ty = e.file_type().expect("a file type");
        if ty.is_dir() {
            walk(&e.path(), &path, out);
        } else if ty.is_file() {
            out.push((path, e.path()));
        }
    }
}

/// The passkey wallet every node serves at `/wallet/` (src/wallet.rs): the static export
/// `npm run build:wallet` writes to web/out (or `BLOCKULA_WALLET_DIR`), compiled in as a table of
/// files, text gzipped. Without an export the table is empty and `/wallet/` says how to get one,
/// so `cargo install --path node` from a plain clone still builds.
fn wallet() {
    use std::io::Write;
    println!("cargo:rerun-if-env-changed=BLOCKULA_WALLET_DIR");
    println!("cargo:rustc-check-cfg=cfg(blockula_wallet_table)");
    let manifest =
        PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let explicit = std::env::var_os("BLOCKULA_WALLET_DIR")
        .filter(|v| !v.is_empty())
        .map(PathBuf::from);
    let dir = explicit
        .clone()
        .unwrap_or_else(|| manifest.join("../web/out"));
    let built = dir.join("index.html").is_file();
    if let Some(d) = &explicit {
        assert!(
            built,
            "BLOCKULA_WALLET_DIR={} has no index.html: point it at the wallet export (npm run build:wallet writes web/out)",
            d.display()
        );
    }
    // Watch the export only when it exists: a missing path would rerun this, and rebuild the
    // crate, every time. `npm run build:wallet` touches this file, so a first export is noticed.
    if built {
        println!("cargo:rerun-if-changed={}", dir.display());
    }
    let mut files = Vec::new();
    if built {
        walk(&dir, "", &mut files);
    }
    let store = out_dir.join("wallet");
    let _ = std::fs::remove_dir_all(&store);
    std::fs::create_dir_all(&store).expect("OUT_DIR/wallet");
    let mut table = String::from(
        "/// Generated by build.rs: (path in the export, gzipped, bytes), sorted by path.\npub static WALLET_FILES: &[(&str, bool, &[u8])] = &[\n",
    );
    for (i, (path, src)) in files.iter().enumerate() {
        let bytes = std::fs::read(src).unwrap_or_else(|e| panic!("reading {}: {e}", src.display()));
        let gz = compressible(path);
        let data = if gz {
            // No name and mtime 0 in the header: the same export gives the same bytes.
            let mut z = flate2::GzBuilder::new()
                .mtime(0)
                .write(Vec::new(), flate2::Compression::best());
            z.write_all(&bytes).expect("in memory");
            z.finish().expect("in memory")
        } else {
            bytes
        };
        let stored = store.join(format!("{i}"));
        std::fs::write(&stored, data).expect("writing the wallet table");
        // Paths from OUT_DIR, never absolute ones: the generated source must be the same text in
        // any checkout, or the binary differs (release builds are reproduced from another path).
        table.push_str(&format!(
            "    ({path:?}, {gz}, include_bytes!(concat!(env!(\"OUT_DIR\"), \"/wallet/{i}\"))),\n"
        ));
    }
    table.push_str("];\n");
    let generated = out_dir.join("wallet_files.rs");
    std::fs::write(&generated, table).expect("writing wallet_files.rs");
    println!("cargo:rustc-cfg=blockula_wallet_table");
}
